namespace Olympus.Core.Time
{
    /// <summary>
    /// 게임 안의 "지금"은 전부 이 인터페이스를 지난다.
    ///
    /// 왜 이렇게 두는가 — 지금은 서버가 없어서 로컬 시간을 쓰지만, 건설·생산 타이머는
    /// 결국 서버 권위여야 한다(로컬 시간을 그대로 믿으면 기기 시계를 돌려서 타이머를
    /// 건너뛸 수 있다). 시간을 읽는 자리가 코드 곳곳에 흩어져 있으면 서버를 붙이는 순간
    /// 전수 조사가 되므로, 관문을 하나로 모아 구현만 갈아끼울 수 있게 만든다.
    ///
    /// 단위는 유닉스 밀리초로 고정한다. 서버가 내려주는 형태가 그렇고,
    /// DateTime/시간대 변환이 끼어들 틈을 없앤다.
    /// </summary>
    public interface IClock
    {
        long NowUnixMs { get; }
    }
}
